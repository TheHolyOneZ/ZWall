use naga::back::glsl;
use std::{path::PathBuf, process::Command};

fn qt_variant(src: &str) -> String {
    let common = zwall_render::COMMON.replace("struct Frame {", "struct Frame {\n    qt_Matrix: mat4x4f,\n    qt_Opacity: f32,");

    let vs_start = common.find("@vertex").expect("vertex entry");
    let vs_end = vs_start + common[vs_start..].find("\n}\n").expect("vertex end") + 3;
    let common = format!("{}{}", &common[..vs_start], &common[vs_end..]);
    let body = src.replace("@fragment\nfn fs_main(@builtin(position) pos: vec4f) -> @location(0) vec4f", "fn zwall_main(pos: vec4f) -> vec4f");
    assert!(body.contains("fn zwall_main"), "unexpected fragment signature");
    format!(
        "{common}\n{body}\n@fragment\nfn fs_main(@location(0) qt_uv: vec2f) -> @location(0) vec4f {{\n    return zwall_main(vec4f(qt_uv * F.resolution, 0.0, 1.0)) * F.qt_Opacity;\n}}\n"
    )
}

fn to_glsl(name: &str, wgsl: &str) -> String {
    let module = naga::front::wgsl::parse_str(wgsl).unwrap_or_else(|e| panic!("{name}: {}", e.emit_to_string(wgsl)));
    let info = naga::valid::Validator::new(naga::valid::ValidationFlags::all(), naga::valid::Capabilities::all()).validate(&module).unwrap_or_else(|e| panic!("{name}: {e:?}"));
    let mut out = String::new();
    let options = glsl::Options { version: glsl::Version::Desktop(440), writer_flags: glsl::WriterFlags::empty(), ..Default::default() };
    let pipeline = glsl::PipelineOptions { shader_stage: naga::ShaderStage::Fragment, entry_point: "fs_main".into(), multiview: None };
    let mut w = glsl::Writer::new(&mut out, &module, &info, &options, &pipeline, naga::proc::BoundsCheckPolicies::default()).unwrap();
    w.write().unwrap();
    out
}

fn qt_interface(glsl: &str) -> String {
    let start = glsl.find("struct Frame {").expect("Frame struct");
    let end = start + glsl[start..].find("};").expect("struct end") + 2;
    let members = glsl[start + "struct Frame {".len()..end - 2].replace("mat4x4 ", "mat4 ");
    let block = format!("layout(std140, binding = 0) uniform buf {{{members}}} F;");
    let mut out = format!("{}{}{}", &glsl[..start], block, &glsl[end..]);
    let old_block = out.find("layout(std140) uniform Frame_block_0Fragment").expect("naga block");
    let old_end = old_block + out[old_block..].find(";\n").expect("block end") + 2;
    out.replace_range(old_block..old_end, "");
    out = out.replace("_group_0_binding_0_fs.", "F.");

    out = out.replace("_vs2fs_location0", "qt_TexCoord0").replace("_fs2p_location0", "fragColor");
    out = out.replace("uniform sampler2D _group_0_binding_1_fs;", "layout(binding = 1) uniform sampler2D source;").replace("_group_0_binding_1_fs", "source");
    out = out.replace("uniform sampler2D _group_0_binding_3_fs;", "layout(binding = 3) uniform sampler2D depthMap;").replace("_group_0_binding_3_fs", "depthMap");
    out = out.replace("uniform sampler2D _group_0_binding_4_fs;", "layout(binding = 4) uniform sampler2D motionMap;").replace("_group_0_binding_4_fs", "motionMap");
    assert!(!out.contains("_group_0_binding"), "unmapped binding left:\n{out}");
    out
}

fn main() {
    let out = PathBuf::from(std::env::args().nth(1).unwrap_or_else(|| "shaders-qt".into()));
    std::fs::create_dir_all(&out).unwrap();
    let only = std::env::args().nth(2);
    let layers = zwall_render::LAYERS.iter().map(|(n, s)| (format!("layer-{n}"), *s));
    for (name, src) in zwall_render::PRESETS.iter().map(|(n, s)| (n.to_string(), *s)).chain(layers).chain([("photo".to_string(), zwall_render::PHOTO)]) {
        let name = name.as_str();
        if only.as_deref().is_some_and(|o| o != name) {
            continue;
        }
        let glsl = qt_interface(&to_glsl(name, &qt_variant(src)));
        let frag = out.join(format!("{name}.frag"));
        std::fs::write(&frag, format!("// Generated by `cargo run -p zwall-render --example qt_shaders`. Do not edit.\n{glsl}")).unwrap();
        let qsb = std::env::var("QSB").unwrap_or_else(|_| "/usr/lib/qt6/bin/qsb".into());
        let status = Command::new(&qsb).args(["--glsl", "300es,150,330", "--hlsl", "50", "--msl", "12", "-o"]).arg(frag.with_extension("frag.qsb")).arg(&frag).status();
        match status {
            Ok(s) if s.success() => println!("{name}: ok"),
            Ok(s) => panic!("{name}: qsb failed ({s})"),
            Err(e) => println!("{name}: GLSL written, qsb unavailable ({e})"),
        }
    }
}
